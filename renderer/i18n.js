let language = 'en';
function setLanguage(value) { language = value === 'it' ? 'it' : 'en'; document.documentElement.lang = language; }
function t(key, ...args) {
  const value = (DICT[language] && DICT[language][key]) || DICT.en[key] || key;
  return typeof value === 'function' ? value(...args) : value;
}

